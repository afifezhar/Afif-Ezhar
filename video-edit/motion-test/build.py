"""Writes index.html for the Style D motion test: hook H4 -> opening line -> star wipe -> statue b-roll.

All times are seconds in this clip. Word times come from the Take A Whisper transcript, re-based to each clip.
Run from video-edit/motion-test:  python3 build.py   (then grade the videos, see ../STORYBOARD.md)
"""

HOOK_SRC, HOOK_LEN = 122.22, 5.80      # "Korang sendiri masih percaya ke dengan AI generated product review ni?"
OPEN_SRC, OPEN_LEN = 1.72, 4.40        # "AI sekarang dah boleh buat video yang nampak real, nampak perfect"
MG_LEN = 3.50                          # "Tapi persoalannya, orang masih percaya ke?" over b-roll
OPEN_AT = HOOK_LEN
MG_AT = OPEN_AT + OPEN_LEN
TOTAL = round(MG_AT + MG_LEN, 2)


def hook(t):
    return round(t - HOOK_SRC, 2)


def opening(t):
    return round(t - OPEN_SRC + OPEN_AT, 2)


# (id, lines, show, hide, word start times). A line is (css class, words).
PHRASES = [
    ("p1", [("ks", "korang sendiri masih"), ("kserif i", "percaya ke")], 0.0, hook(124.88),
     [hook(t) for t in (122.22, 123.22, 123.46, 124.14, 124.68)]),
    ("p2", [("ks", "dengan"), ("kit", "AI generated"), ("ks", "product review ni?")], hook(124.90), HOOK_LEN - 0.04,
     [hook(t) for t in (124.90, 125.24, 126.02, 126.50, 127.22, 127.68)]),
    ("p3", [("ks", "AI sekarang"), ("kbig", "dah boleh")], OPEN_AT, opening(3.52),
     [opening(t) for t in (1.72, 2.36, 2.76, 3.24)]),
    ("p4", [("ks", "buat video yang"), ("kit", "nampak real,")], opening(3.56), opening(5.34),
     [opening(t) for t in (3.56, 3.96, 4.36, 4.54, 5.04)]),
    ("p5", [("ks", "nampak"), ("kserif", "perfect.")], opening(5.38), MG_AT - 0.05,
     [opening(t) for t in (5.38, 5.88)]),
]


def phrase_html(pid, lines):
    out = []
    for cls, text in lines:
        words = " ".join(f'<span class="w">{w}</span>' for w in text.split())
        out.append(f'<div class="{cls}">{words}</div>')
    return f'      <div id="{pid}" class="ov kold">{"".join(out)}</div>'


def mg(t):
    """Time inside the b-roll, given the Take A source time of the spoken word (b-roll starts at A 6.12)."""
    return round(t - 6.12 + MG_AT, 2)


html = f"""<!doctype html>
<html lang="ms" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="assets/gsap.min.js"></script>
    <link rel="stylesheet" href="assets/style-d.css" />
    <style>
      .kold {{ opacity: 0; }}
      .kold .w {{ opacity: 0; }}
      #eyebrow .c {{ opacity: 0; }}
      #mgtest .wd {{ display: inline-block; opacity: 0; }}
      #tstar {{ position: absolute; right: -150px; top: -170px; width: 520px; height: 520px; z-index: 20; }}
    </style>
  </head>
  <body>
    <!-- Style D motion test ({TOTAL} s): hook H4 -> opening line -> star wipe -> b-roll. Generated by build.py. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{TOTAL}" data-width="1080" data-height="1920">
      <video id="v-hook" class="plate zoom-110 clip" src="assets/media/hook.mp4" muted data-start="0" data-duration="{HOOK_LEN}" data-track-index="0"></video>
      <video id="v-open" class="plate clip" src="assets/media/open.mp4" muted data-start="{OPEN_AT}" data-duration="{OPEN_LEN}" data-track-index="0"></video>
      <div id="fade" class="fade"></div>

{chr(10).join(phrase_html(pid, lines) for pid, lines, *_ in PHRASES)}

      <div id="mgtest" class="mg clip" data-start="{MG_AT}" data-duration="{MG_LEN}" data-track-index="1">
        <div id="eyebrow" class="ov eyebrow" style="top:250px"></div>
        <div class="ov mgbig" style="top:310px"><span class="wd" id="m-orang">orang</span><br><span class="wd" id="m-masih">masih</span></div>
        <img id="statue" class="stock" src="assets/stock/statue.png" alt="" style="left:330px;top:560px;height:1240px" />
        <div class="ov mgbig" style="top:910px;z-index:3"><span class="wd" id="m-percaya">percaya</span><br><span class="wd" id="m-ke">ke?</span></div>
        <div class="ov barcode" style="left:64px;top:1250px;width:220px;height:48px"></div>
      </div>
      <svg id="tstar" viewBox="0 0 100 100"><path style="fill: var(--star)" d="M50 0 C54 38 62 46 100 50 C62 54 54 62 50 100 C46 62 38 54 0 50 C38 46 46 38 50 0Z"/></svg>

      <audio id="a-voice" src="assets/media/voice.m4a" data-start="0" data-duration="{TOTAL}" data-track-index="2"></audio>
      <audio id="a-music" src="assets/media/music.m4a" data-start="0" data-duration="{TOTAL}" data-volume="0.16" data-fade-out="0.8" data-track-index="3"></audio>
      <audio id="a-whoosh" src="assets/media/whoosh.mp3" data-start="{round(MG_AT - 0.3, 2)}" data-duration="1" data-volume="0.55" data-track-index="4"></audio>
      <audio id="a-type" src="assets/media/type.mp3" data-start="{round(MG_AT + 0.05, 2)}" data-duration="1.5" data-volume="0.3" data-track-index="5"></audio>
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      const reveal = (el, t) => tl.fromTo(el, {{ opacity: 0, y: 22, scale: 0.94 }}, {{ opacity: 1, y: 0, scale: 1, duration: 0.16, ease: "power2.out", immediateRender: false }}, t);

      // [phrase, show, hide, word start times]
      const phrases = {[[f"#{pid}", show, hide, times] for pid, _, show, hide, times in PHRASES]};
      for (const [sel, show, hide, times] of phrases) {{
        tl.set(sel, {{ opacity: 1 }}, show);
        document.querySelectorAll(sel + " .w").forEach((w, i) => reveal(w, times[i]));
        tl.to(sel, {{ opacity: 0, duration: 0.1 }}, hide);
      }}

      // Star wipe: grows from the corner to cover the frame, then settles back as a corner ornament.
      tl.fromTo("#tstar", {{ scale: 0, rotation: -120, transformOrigin: "50% 50%" }}, {{ scale: 38, rotation: 0, duration: 0.24, ease: "power3.in" }}, {round(MG_AT - 0.24, 2)});
      tl.to("#tstar", {{ scale: 1, rotation: 20, duration: 0.45, ease: "power3.out" }}, {MG_AT});

      // Eyebrow typed in time with "Tapi persoalannya," (A 6.12-7.82).
      const eyebrow = document.getElementById("eyebrow");
      const text = "Tapi persoalannya,";
      for (const ch of text) {{ const s = document.createElement("span"); s.className = "c"; s.textContent = ch; eyebrow.appendChild(s); }}
      eyebrow.querySelectorAll(".c").forEach((c, i) => tl.set(c, {{ opacity: 1 }}, {round(MG_AT + 0.05, 2)} + i * (1.55 / text.length)));

      // Statue rises in; headline words slide in on their spoken word.
      tl.fromTo("#statue", {{ y: 260, opacity: 0 }}, {{ y: 0, opacity: 1, duration: 0.7, ease: "power3.out" }}, {round(MG_AT + 0.15, 2)});
      const slide = (sel, t) => tl.fromTo(sel, {{ opacity: 0, x: -60 }}, {{ opacity: 1, x: 0, duration: 0.22, ease: "power3.out", immediateRender: false }}, t);
      slide("#m-orang", {mg(7.94)}); slide("#m-masih", {mg(8.40)}); slide("#m-percaya", {mg(8.72)}); slide("#m-ke", {mg(9.10)});

      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""
open("index.html", "w").write(html)
print("total", TOTAL)
